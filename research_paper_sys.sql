
CREATE TABLE researcher (
    researcher_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    affiliation VARCHAR(150)
);

CREATE TABLE research_paper (
    paper_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(250) NOT NULL,
    abstract TEXT,
    submitted_on DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
    CONSTRAINT chk_paper_status CHECK (
        status IN (
            'SUBMITTED', 'UNDER_REVIEW', 'ACCEPTED',
            'REJECTED', 'PUBLISHED'
        )
    )
);

CREATE TABLE author_paper (
    researcher_id INTEGER NOT NULL,
    paper_id INTEGER NOT NULL,
    author_order INTEGER NOT NULL CHECK (author_order >= 1),
    PRIMARY KEY (researcher_id, paper_id),
    UNIQUE (paper_id, author_order),
    FOREIGN KEY (researcher_id) REFERENCES researcher(researcher_id),
    FOREIGN KEY (paper_id) REFERENCES research_paper(paper_id)
);

CREATE TABLE reviewer (
    reviewer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    expertise VARCHAR(150)
);

CREATE TABLE review_assignment (
    assignment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_id INTEGER NOT NULL REFERENCES research_paper(paper_id),
    reviewer_id INTEGER NOT NULL REFERENCES reviewer(reviewer_id),
    assigned_on DATE NOT NULL DEFAULT CURRENT_DATE,
    due_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ASSIGNED',
    UNIQUE (paper_id, reviewer_id),
    CHECK (status IN ('ASSIGNED', 'COMPLETED', 'CANCELLED')),
    CHECK (due_date IS NULL OR due_date >= assigned_on)
);

CREATE TABLE review (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id INTEGER NOT NULL UNIQUE
        REFERENCES review_assignment(assignment_id),
    recommendation VARCHAR(20) NOT NULL,
    score INTEGER CHECK (score IS NULL OR score BETWEEN 1 AND 5),
    comments VARCHAR(2000),
    reviewed_on DATE NOT NULL DEFAULT CURRENT_DATE,
    CHECK (
        recommendation IN (
            'ACCEPT', 'MINOR_REVISION', 'MAJOR_REVISION', 'REJECT'
        )
    )
);

CREATE TABLE publication (
    publication_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_id INTEGER NOT NULL UNIQUE REFERENCES research_paper(paper_id),
    venue VARCHAR(200) NOT NULL,
    publication_year INTEGER NOT NULL CHECK (
        publication_year BETWEEN 1900 AND 2100
    ),
    doi VARCHAR(200) UNIQUE
);

CREATE TABLE citation (
    citation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    citing_paper_id INTEGER NOT NULL REFERENCES research_paper(paper_id),
    cited_paper_id INTEGER NOT NULL REFERENCES research_paper(paper_id),
    UNIQUE (citing_paper_id, cited_paper_id),
    CHECK (citing_paper_id <> cited_paper_id)
);





