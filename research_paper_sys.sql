--Find published papers
SELECT paper_id, title, submitted_on
FROM research_paper
WHERE status = 'PUBLISHED'
ORDER BY submitted_on DESC;


--Display papers with their authors
SELECT p.title, r.name AS author_name
FROM research_paper p
INNER JOIN author_paper ap ON p.paper_id = ap.paper_id
INNER JOIN researcher r ON ap.researcher_id = r.researcher_id;


--Count papers by status
SELECT status, COUNT(*) AS total_papers
FROM research_paper
GROUP BY status;


-- Find researchers who have authored at least one paper
SELECT r.researcher_id, r.name, COUNT(ap.paper_id) AS total_papers
FROM researcher r
JOIN author_paper ap ON r.researcher_id = ap.researcher_id
GROUP BY r.researcher_id, r.name
HAVING COUNT(ap.paper_id) >= 1;


--Find papers without review assignments
SELECT p.paper_id, p.title
FROM research_paper p
LEFT JOIN review_assignment ra ON p.paper_id = ra.paper_id
WHERE ra.assignment_id IS NULL;


--Display reviews with paper and reviewer details
SELECT p.title, rv.name AS reviewer_name,
       rev.recommendation, rev.score
FROM review rev
JOIN review_assignment ra ON rev.assignment_id = ra.assignment_id
JOIN research_paper p ON ra.paper_id = p.paper_id
JOIN reviewer rv ON ra.reviewer_id = rv.reviewer_id;


--Calculate average review score per paper
SELECT p.title, ROUND(AVG(rev.score), 2) AS average_score
FROM research_paper p
JOIN review_assignment ra ON p.paper_id = ra.paper_id
JOIN review rev ON ra.assignment_id = rev.assignment_id
GROUP BY p.paper_id, p.title
ORDER BY average_score DESC;


--Find papers with scores above the overall average
SELECT p.title, rev.score
FROM research_paper p
JOIN review_assignment ra ON p.paper_id = ra.paper_id
JOIN review rev ON ra.assignment_id = rev.assignment_id
WHERE rev.score > (SELECT AVG(score) FROM review);


--Find researchers who have authored papers
SELECT r.researcher_id, r.name
FROM researcher r
WHERE EXISTS (
    SELECT 1
    FROM author_paper ap
    WHERE ap.researcher_id = r.researcher_id
);


--Display papers and the papers they cite
SELECT citing.title AS citing_paper,
       cited.title AS cited_paper
FROM citation c
JOIN research_paper citing ON c.citing_paper_id = citing.paper_id
JOIN research_paper cited ON c.cited_paper_id = cited.paper_id;


--Count citations received by each paper
SELECT p.paper_id, p.title,
       COUNT(c.citation_id) AS citation_count
FROM research_paper p
LEFT JOIN citation c ON p.paper_id = c.cited_paper_id
GROUP BY p.paper_id, p.title
ORDER BY citation_count DESC;


--Display publication venues used in the system
SELECT DISTINCT venue
FROM publication
ORDER BY venue;


--Categorize papers based on their review scores
SELECT p.title, rev.score,
       CASE
           WHEN rev.score >= 4 THEN 'High Score'
           WHEN rev.score = 3 THEN 'Average Score'
           ELSE 'Low Score'
       END AS score_category
FROM research_paper p
JOIN review_assignment ra ON p.paper_id = ra.paper_id
JOIN review rev ON ra.assignment_id = rev.assignment_id;


