CREATE OR REPLACE FUNCTION mark_assignment_completed()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE review_assignment
    SET status = 'COMPLETED'
    WHERE assignment_id = NEW.assignment_id;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_review_completed
AFTER INSERT ON review
FOR EACH ROW
EXECUTE FUNCTION mark_assignment_completed();



CREATE OR REPLACE FUNCTION mark_paper_published()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE research_paper
    SET status = 'PUBLISHED'
    WHERE paper_id = NEW.paper_id;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_paper_published
AFTER INSERT ON publication
FOR EACH ROW
EXECUTE FUNCTION mark_paper_published();




CREATE OR REPLACE PROCEDURE assign_reviewer(
    p_paper_id INTEGER,
    p_reviewer_id INTEGER,
    p_due_date DATE
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM research_paper
        WHERE paper_id = p_paper_id
    ) THEN
        RAISE EXCEPTION 'Research paper % does not exist', p_paper_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM reviewer
        WHERE reviewer_id = p_reviewer_id
    ) THEN
        RAISE EXCEPTION 'Reviewer % does not exist', p_reviewer_id;
    END IF;

    IF p_due_date < CURRENT_DATE THEN
        RAISE EXCEPTION 'Due date cannot be in the past';
    END IF;

    INSERT INTO review_assignment (
        paper_id,
        reviewer_id,
        due_date,
        status
    )
    VALUES (
        p_paper_id,
        p_reviewer_id,
        p_due_date,
        'ASSIGNED'
    );
END;
$$;

