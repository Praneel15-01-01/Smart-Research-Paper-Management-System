CREATE OR REPLACE PROCEDURE update_paper_decision(
    p_paper_id INTEGER,
    p_status VARCHAR(20)
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_status NOT IN ('ACCEPTED', 'REJECTED') THEN
        RAISE EXCEPTION
            'Invalid decision. Use ACCEPTED or REJECTED.';
    END IF;

    UPDATE research_paper
    SET status = p_status
    WHERE paper_id = p_paper_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Research paper % does not exist', p_paper_id;
    END IF;
END;
$$;





CREATE OR REPLACE FUNCTION researcher_publication_count(
    p_researcher_id INTEGER
)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_count INTEGER;
BEGIN
    SELECT COUNT(DISTINCT pub.publication_id)
    INTO v_count
    FROM author_paper ap
    JOIN publication pub
        ON ap.paper_id = pub.paper_id
    WHERE ap.researcher_id = p_researcher_id;

    RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION completed_review_count(
    p_paper_id INTEGER
)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_count INTEGER;
BEGIN
    SELECT COUNT(r.review_id)
    INTO v_count
    FROM review_assignment ra
    JOIN review r
        ON ra.assignment_id = r.assignment_id
    WHERE ra.paper_id = p_paper_id;

    RETURN v_count;
END;
$$;

DO $$
DECLARE
    assignment_record RECORD;

    assignment_cursor CURSOR FOR
        SELECT
            ra.assignment_id,
            ra.paper_id,
            p.title,
            ra.reviewer_id,
            ra.due_date
        FROM review_assignment ra
        JOIN research_paper p
            ON ra.paper_id = p.paper_id
        LEFT JOIN review r
            ON ra.assignment_id = r.assignment_id
        WHERE r.review_id IS NULL
        ORDER BY ra.assignment_id;

BEGIN
    OPEN assignment_cursor;

    LOOP
        FETCH assignment_cursor INTO assignment_record;
        EXIT WHEN NOT FOUND;

        RAISE NOTICE
            'Assignment ID: %, Paper ID: %, Title: %, Reviewer ID: %, Due Date: %',
            assignment_record.assignment_id,
            assignment_record.paper_id,
            assignment_record.title,
            assignment_record.reviewer_id,
            assignment_record.due_date;
    END LOOP;

    CLOSE assignment_cursor;
END;
$$;





